# 讀取整數電力使用量 usage (單位: kWh)
usage = int(input())

# 依據三個區間進行累進費率分段計算
if usage <= 120:
    bill = usage * 2.10
elif usage <= 500:
    # 前 120 度以 2.10 計算，超過 120 度的部分以 3.02 計算
    bill = (120 * 2.10) + (usage - 120) * 3.02
else:
    # 前 120 度以 2.10 計算，121~500 度(共 380 度)以 3.02 計算，超過 500 度以 4.39 計算
    bill = (120 * 2.10) + (380 * 3.02) + (usage - 500) * 4.39

# 依照範例格式輸出，加上 "NT$" 前綴並四捨五入至小數點後一位
print(f"NT${bill:.1f}")